const fail = () => { throw new Error("Dedicated Linux service verification preflight refused."); };

export function parsePackageArgument(args) {
  if (!Array.isArray(args) || args.length !== 2 || args[0] !== "--package" || typeof args[1] !== "string" ||
    !isAbsolute(args[1]) || /[\0\r\n]/.test(args[1]) || args[1].length > 4096) fail();
  return args[1];
}
export function validateInvocation({ platform, uid, username, optIn, home }) {
  if (platform !== "linux" || !Number.isSafeInteger(uid) || uid < 1 || username !== "spillway-ci" ||
    optIn !== "1" || typeof home !== "string" || !isAbsolute(home) || /[\0\r\n]/.test(home)) fail();
}
/** lstat deliberately catches dangling links; no absent-path creation here. */
export async function assertAbsent(path) {
  try { await lstat(path); }
  catch (error) { if (error?.code === "ENOENT") return; fail(); }
  fail();
}
export function servicePaths(home, uid) {
  return [join(home, ".config", "systemd", "user"), join(`/run/user/${uid}`, "systemd", "user")].flatMap(unitNamespacePaths);
}
export function unitNamespacePaths(path) {
  return [join(path, unitName), join(path, "default.target.wants", unitName),
    join(path, `${unitName}.d`), join(path, "agent-.service.d"), join(path, "service.d")];
}
export function parseUnitPaths(output) {
  if (typeof output !== "string" || output.length > 16384) fail();
  const text = output.replace(/\n$/, "");
  if (!text || /[\0\r\n\\"']/.test(text)) fail();
  const paths = text.split(" ");
  if (paths.length > 64 || paths.some(path => !isAbsolute(path) || path.length > 4096 || path !== resolve(path) || /[\x00-\x20\x7f]/.test(path))) fail();
  return [...new Set(paths)];
}
