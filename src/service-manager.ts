import { constants, realpathSync } from "node:fs";
import {
  chmod,
  lstat,
  mkdir,
  open,
  realpath,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { execFile } from "node:child_process";
import { homedir } from "node:os";
import { dirname, isAbsolute, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import { loadConfig, defaultConfigPath } from "./config.js";
import { SpillwayError } from "./contracts.js";

export type ServicePlatform = "darwin" | "linux";
export interface ManagerCommand {
  command: string;
  args: string[];
  env: NodeJS.ProcessEnv;
}
export interface ManagerResult {
  exitCode: number;
  stdout: string;
}
export type ManagerExecutor = (input: ManagerCommand) => Promise<ManagerResult>;
export interface ManagerOptions {
  platform?: ServicePlatform;
  /** Test seam: production uses the real user's home, uid and argument-array executor. */
  homeDir?: string;
  uid?: number;
  executor?: ManagerExecutor;
}
export interface InstallOptions extends ManagerOptions {
  configPath?: string;
  nodePath?: string;
  cliPath?: string;
  environmentPath?: string;
  start?: boolean;
}
export interface ServiceDefinition {
  nodePath: string;
  cliPath: string;
  configPath: string;
  environmentPath: string;
  workingDir: string;
  stdoutPath: string;
  stderrPath: string;
}
export const SERVICE_LABEL = "com.agent-spillway";
export const SERVICE_UNIT = "agent-spillway.service";
const marker = "Generated by Agent Spillway service-manager v1";
const hasControl = (value: string): boolean =>
  [...value].some(
    (char) => char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127,
  );
const safeText = (value: string): string => {
  if (!value || hasControl(value))
    throw new SpillwayError(
      "service_path",
      "Service paths must not contain control characters.",
    );
  return value;
};
function absolute(value: string): string {
  safeText(value);
  if (!isAbsolute(value))
    throw new SpillwayError("service_path", "Service paths must be absolute.");
  return value;
}
function pathValue(value: string): string {
  safeText(value);
  for (const path of value.split(":")) absolute(path);
  return value;
}
const xml = (value: string): string =>
  safeText(value).replace(
    /[&<>"']/g,
    (char) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&apos;",
      })[char]!,
  );
const unit = (value: string): string =>
  `"${safeText(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%")}"`;
const unitPath = (value: string): string => {
  if (value.trim() !== value || value.endsWith("\\"))
    throw new SpillwayError(
      "service_path",
      "Linux service directories/log paths cannot end in whitespace or a backslash.",
    );
  return safeText(value).replace(/%/g, "%%");
};
function validateDefinition(definition: ServiceDefinition): void {
  for (const [key, value] of Object.entries(definition)) {
    if (key === "environmentPath") pathValue(value);
    else absolute(value);
  }
}

/** env -i ensures daemon/session manager variables cannot become provider credentials. */
export function renderLaunchAgent(definition: ServiceDefinition): string {
  validateDefinition(definition);
  const args = [
    "/usr/bin/env",
    "-i",
    `PATH=${definition.environmentPath}`,
    definition.nodePath,
    definition.cliPath,
    "--config",
    definition.configPath,
    "serve",
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- ${marker} -->\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n<key>Label</key><string>${SERVICE_LABEL}</string>\n<key>ProgramArguments</key><array>${args.map((arg) => `<string>${xml(arg)}</string>`).join("")}</array>\n<key>WorkingDirectory</key><string>${xml(definition.workingDir)}</string>\n<key>StandardOutPath</key><string>${xml(definition.stdoutPath)}</string>\n<key>StandardErrorPath</key><string>${xml(definition.stderrPath)}</string>\n<key>RunAtLoad</key><true/>\n<key>KeepAlive</key><true/>\n<key>ThrottleInterval</key><integer>10</integer>\n<key>ExitTimeOut</key><integer>60</integer>\n<key>Umask</key><integer>63</integer>\n</dict></plist>\n`;
}
export function renderUserUnit(definition: ServiceDefinition): string {
  validateDefinition(definition);
  // ':' disables systemd $ expansion; %% escapes its independent specifier expansion.
  const args = [
    "-i",
    `PATH=${definition.environmentPath}`,
    definition.nodePath,
    definition.cliPath,
    "--config",
    definition.configPath,
    "serve",
  ];
  return `# ${marker}\n[Unit]\nDescription=Agent Spillway per-user queue\nStartLimitIntervalSec=60\nStartLimitBurst=5\n\n[Service]\nType=exec\nExecStart=:/usr/bin/env ${args.map(unit).join(" ")}\nWorkingDirectory=${unitPath(definition.workingDir)}\nStandardOutput=append:${unitPath(definition.stdoutPath)}\nStandardError=append:${unitPath(definition.stderrPath)}\nRestart=on-failure\nRestartSec=10\nTimeoutStopSec=60\nUMask=0077\n\n[Install]\nWantedBy=default.target\n`;
}
const execute: ManagerExecutor = (input) =>
  new Promise((resolve, reject) => {
    execFile(
      input.command,
      input.args,
      { env: input.env, timeout: 15000, maxBuffer: 64 * 1024 },
      (error, stdout) => {
        if (error && typeof error.code !== "number") {
          reject(
            new SpillwayError(
              "service_manager",
              "Cannot contact the per-user service manager.",
            ),
          );
          return;
        }
        resolve({ exitCode: error ? Number(error.code) : 0, stdout });
      },
    );
  });
function context(options: ManagerOptions) {
  if (!options.executor && process.getuid?.() === 0) {
    throw new SpillwayError(
      "service_user",
      "Install Spillway as a regular user, never root.",
    );
  }
  const platform = options.platform ?? process.platform;
  if (platform !== "darwin" && platform !== "linux")
    throw new SpillwayError(
      "service_platform",
      "Per-user services support macOS and Linux only.",
    );
  const uid = options.uid ?? process.getuid?.();
  if (!uid || !Number.isSafeInteger(uid) || uid < 1)
    throw new SpillwayError(
      "service_user",
      "Install Spillway as a regular user, never root.",
    );
  const home = realpathSync(absolute(options.homeDir ?? homedir()));
  const path =
    platform === "darwin"
      ? join(home, "Library", "LaunchAgents", `${SERVICE_LABEL}.plist`)
      : join(home, ".config", "systemd", "user", SERVICE_UNIT);
  const runner = options.executor ?? execute;
  const env: NodeJS.ProcessEnv = {
    PATH: "/usr/bin:/bin:/usr/sbin:/sbin",
    HOME: home,
  };
  if (platform === "linux") env.XDG_RUNTIME_DIR = `/run/user/${uid}`;
  const call = async (
    args: string[],
    allowFailure = false,
  ): Promise<ManagerResult> => {
    const result = await runner({
      command: platform === "darwin" ? "/bin/launchctl" : "/usr/bin/systemctl",
      args: platform === "darwin" ? args : ["--user", ...args],
      env,
    });
    if (result.exitCode !== 0 && !allowFailure)
      throw new SpillwayError(
        "service_manager",
        "Per-user service manager rejected the operation. Inspect private service logs.",
      );
    return result;
  };
  return {
    platform,
    uid,
    path,
    call,
    target: `gui/${uid}/${SERVICE_LABEL}`,
    domain: `gui/${uid}`,
  };
}
async function noSymlinkAncestors(path: string): Promise<void> {
  let ancestor = path;
  while (true) {
    try {
      if ((await lstat(ancestor)).isSymbolicLink())
        throw new SpillwayError(
          "unsafe_service_file",
          "Managed service paths must not contain symlinks.",
        );
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    if (dirname(ancestor) === ancestor) return;
    ancestor = dirname(ancestor);
  }
}
async function ensureDirectory(path: string): Promise<void> {
  await noSymlinkAncestors(path);
  // Inspect each existing ancestor: mkdir(recursive) would otherwise follow a substituted symlink.
  const parent = dirname(path);
  if (parent !== path) {
    try {
      const info = await lstat(parent);
      if (info.isSymbolicLink() || !info.isDirectory())
        throw new SpillwayError(
          "unsafe_service_file",
          "Service directory must not be a symlink.",
        );
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      await ensureDirectory(parent);
    }
  }
  await mkdir(path, { recursive: true, mode: 0o700 });
  const info = await lstat(path);
  if (
    !info.isDirectory() ||
    info.isSymbolicLink() ||
    (process.getuid && info.uid !== process.getuid())
  )
    throw new SpillwayError(
      "unsafe_service_file",
      "Service directory must be owned by the current user and not a symlink.",
    );
  await chmod(path, 0o700);
}
async function readOwned(
  path: string,
  platform: ServicePlatform,
): Promise<string | undefined> {
  let handle;
  try {
    await noSymlinkAncestors(path);
    handle = await open(
      path,
      constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK,
    );
    const info = await handle.stat();
    if (
      !info.isFile() ||
      info.nlink !== 1 ||
      info.size > 64 * 1024 ||
      (process.getuid && info.uid !== process.getuid())
    )
      throw new SpillwayError(
        "unsafe_service_file",
        "Service file must be a regular file owned by the current user.",
      );
    const content = await handle.readFile("utf8");
    if (
      !content.includes(marker) ||
      (platform === "darwin"
        ? !content.includes(`<key>Label</key><string>${SERVICE_LABEL}</string>`)
        : !content.startsWith(`# ${marker}\n`))
    ) {
      throw new SpillwayError(
        "unrelated_service_file",
        "Refusing to change an unrelated service file.",
      );
    }
    return content;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    if (error instanceof SpillwayError) throw error;
    throw new SpillwayError(
      "unsafe_service_file",
      "Cannot read the managed service file safely.",
    );
  } finally {
    await handle?.close();
  }
}
async function privateLog(path: string): Promise<void> {
  const file = await open(
    path,
    constants.O_WRONLY |
      constants.O_APPEND |
      constants.O_CREAT |
      constants.O_NOFOLLOW |
      constants.O_NONBLOCK,
    0o600,
  );
  try {
    const info = await file.stat();
    if (
      !info.isFile() ||
      info.nlink !== 1 ||
      (process.getuid && info.uid !== process.getuid())
    )
      throw new SpillwayError(
        "unsafe_service_file",
        "Service logs must be private regular files.",
      );
    await file.chmod(0o600);
  } finally {
    await file.close();
  }
}

export async function installService(
  options: InstallOptions = {},
): Promise<{ platform: ServicePlatform; path: string }> {
  const ctx = context(options);
  const configPath = await realpath(
    absolute(options.configPath ?? defaultConfigPath()),
  );
  const nodePath = await realpath(
    absolute(options.nodePath ?? process.execPath),
  );
  const cliPath = await realpath(
    absolute(
      options.cliPath ?? fileURLToPath(new URL("./cli.js", import.meta.url)),
    ),
  );
  if (
    !(await lstat(nodePath)).isFile() ||
    !(await lstat(cliPath)).isFile() ||
    !cliPath.endsWith(".js")
  )
    throw new SpillwayError(
      "service_path",
      "Install a built JavaScript CLI and a regular Node executable.",
    );
  const config = await loadConfig(configPath);
  const workingDir = join(config.data_dir, "service");
  await ensureDirectory(workingDir);
  const stdoutPath = join(workingDir, "stdout.log");
  const stderrPath = join(workingDir, "stderr.log");
  await privateLog(stdoutPath);
  await privateLog(stderrPath);
  const environmentPath = pathValue(
    options.environmentPath ??
      [
        ...new Set([
          dirname(nodePath),
          join(realpathSync(options.homeDir ?? homedir()), ".local", "bin"),
          "/opt/homebrew/bin",
          "/usr/local/bin",
          "/usr/bin",
          "/bin",
          "/usr/sbin",
          "/sbin",
        ]),
      ].join(":"),
  );
  const definition = {
    configPath,
    nodePath,
    cliPath,
    workingDir,
    stdoutPath,
    stderrPath,
    environmentPath,
  };
  const content =
    ctx.platform === "darwin"
      ? renderLaunchAgent(definition)
      : renderUserUnit(definition);
  await ensureDirectory(dirname(ctx.path));
  const previous = await readOwned(ctx.path, ctx.platform);
  const temp = `${ctx.path}.${randomBytes(8).toString("hex")}.tmp`;
  try {
    await writeFile(temp, content, { mode: 0o600, flag: "wx" });
    if ((await readOwned(ctx.path, ctx.platform)) !== previous)
      throw new SpillwayError(
        "service_changed",
        "Service file changed during installation. Retry after inspecting it.",
      );
    await rename(temp, ctx.path);
  } finally {
    await rm(temp, { force: true });
  }
  if (options.start !== false) await manageService("start", options);
  return { platform: ctx.platform, path: ctx.path };
}

export async function manageService(
  action: "start" | "stop" | "status" | "uninstall",
  options: ManagerOptions = {},
): Promise<unknown> {
  const ctx = context(options);
  const installed = (await readOwned(ctx.path, ctx.platform)) !== undefined;
  if (!installed) {
    if (action === "status" || action === "uninstall")
      return { platform: ctx.platform, installed: false, running: false };
    throw new SpillwayError(
      "service_missing",
      "Install the per-user service first.",
    );
  }
  if (action === "status") {
    const status = await ctx.call(
      ctx.platform === "darwin"
        ? ["print", ctx.target]
        : ["is-active", SERVICE_UNIT],
      true,
    );
    return {
      platform: ctx.platform,
      installed: true,
      running:
        ctx.platform === "darwin"
          ? status.exitCode === 0 && /state = running/.test(status.stdout)
          : status.exitCode === 0 && status.stdout.trim() === "active",
    };
  }
  if (action === "start") {
    if (ctx.platform === "darwin") {
      const status = await ctx.call(["print", ctx.target], true);
      if (status.exitCode === 0) {
        await ctx.call(["bootout", ctx.target]);
      }
      await ctx.call(["bootstrap", ctx.domain, ctx.path]);
    } else {
      await ctx.call(["daemon-reload"]);
      await ctx.call(["enable", SERVICE_UNIT]);
      // Starting an active unit does not apply new pins; restart also starts inactive units.
      await ctx.call(["restart", SERVICE_UNIT]);
    }
  } else {
    if (ctx.platform === "darwin") {
      const status = await ctx.call(["print", ctx.target], true);
      if (status.exitCode === 0) await ctx.call(["bootout", ctx.target]);
    } else {
      await ctx.call(["stop", SERVICE_UNIT]);
      if (action === "uninstall") await ctx.call(["disable", SERVICE_UNIT]);
    }
    if (action === "uninstall") {
      await readOwned(ctx.path, ctx.platform);
      await rm(ctx.path); // Only the service definition; config, logs and queue evidence remain.
      if (ctx.platform === "linux") await ctx.call(["daemon-reload"]);
    }
  }
  return { platform: ctx.platform, action, installed: action !== "uninstall" };
}
